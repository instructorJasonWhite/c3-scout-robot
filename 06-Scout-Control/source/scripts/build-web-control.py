"""Bundle the offline browser controller into a deterministic gzipped flash page."""
from pathlib import Path
import gzip
ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / 'firmware/web'
html = (WEB / 'index.html').read_text(encoding='utf8')
for marker, name in [('@@CORE@@','control-core.js'),('@@APP@@','control-app.js')]:
    html = html.replace(marker,(WEB / name).read_text(encoding='utf8'))
assert '@@' not in html
data = gzip.compress(html.encode('utf8'),compresslevel=9,mtime=0)
header = ['// Generated by scripts/build-web-control.py', '#pragma once', '#include <Arduino.h>',
          'const uint8_t WEB_CONTROL_PAGE[] PROGMEM = {']
header += ['  '+','.join(f'0x{b:02x}' for b in data[i:i+24])+',' for i in range(0,len(data),24)]
header += ['};']
(ROOT/'firmware/ScoutDrive/WebControlPage.h').write_text('\n'.join(header)+'\n')
out = ROOT/'artifacts/web-control';out.mkdir(parents=True,exist_ok=True)
(out/'index.html').write_text(html,encoding='utf8')
assert gzip.decompress(data).decode('utf8') == html
print(f'Browser page: {len(html.encode("utf8")):,} bytes; {len(data):,} bytes compressed in flash.')
